#!/usr/bin/env node
/**
 * theme-lp.css の生成（WPテーマCSSの「LPで使う分だけ」版）
 *
 * 背景（2026-09-04 高速化）:
 *   全LPは WPテーマ style.css のスナップショット assets/css/theme-snapshot.css（minify後 37KB /
 *   gzip 8KB）をレンダーブロックで読んでいるが、LPが実際に使う規則は 1/3 以下
 *   （WP本体・ブロックエディタ・固定ページ・ナビ等の規則が大半）。全LPのHTML/JSに
 *   出てくるクラス・タグ・IDだけを残した theme-lp.css（minify後 ~14KB / gzip 3.5KB）を
 *   生成し、主力LPはこちらを読む。
 *
 * 正本は引き続き theme-snapshot.css（Snapshot WP theme CSS ワークフローが本番と同期）。
 * このファイルは**生成物**で、手で編集しない。theme-snapshot.css・LPのHTML/JS を変えたら
 *   node scripts/build-theme-lp-css.mjs
 * で再生成し、差分が出たら theme-lp.css の ?v= を上げる（check-asset-versions.mjs が見張る）。
 * ci.yml の「生成物のドリフト」ジョブが再生成忘れを止める。
 *
 * 前提: purgecss（npm i --no-save purgecss@7.0.2）。無い環境ではエラー終了する
 * （黙って古い生成物を通さない）。
 *
 * 残す判断は PurgeCSS 既定の「HTML/JSに文字列として現れるクラス・ID・タグ」に加えて、
 *   - JSが後から付けるステート系 (is-* / lp-* / dk-* / cvr-*)
 *   - 属性セレクタを含む規則（input[type=tel] 等。値が動的に変わっても壊れないよう全部残す）
 *   - @keyframes / @font-face / CSS変数
 * を無条件に残す。判断を疑うときは --report で「落とした規則」を一覧できる。
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { join, relative } from "node:path";
import { createRequire } from "node:module";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SRC = join(ROOT, "assets/css/theme-snapshot.css");
const OUT = join(ROOT, "assets/css/theme-lp.css");
const REPORT = process.argv.includes("--report");

let PurgeCSS;
try {
  ({ PurgeCSS } = createRequire(join(ROOT, "package.json"))("purgecss"));
} catch {
  console.error("build-theme-lp-css: purgecss が見つからない。`npm i --no-save purgecss@7.0.2` を実行してから再度。");
  process.exit(1);
}

// 配信されるHTML/JSを全部「内容」として渡す（どのLPが読んでも足りるよう、全LPの和集合で残す）
const SKIP = new Set([".git", "node_modules", "docs", "scripts", "gas-recorder", ".github", ".cursor", ".netlify"]);
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(html|js)$/.test(name)) out.push(p);
  }
  return out;
}
const content = walk(ROOT).sort();

const source = readFileSync(SRC, "utf8");
const srcHash = createHash("sha256").update(source).digest("hex").slice(0, 16);

const [result] = await new PurgeCSS().purge({
  content,
  css: [{ raw: source }],
  safelist: {
    standard: [/^is-/, /^lp-/, /^dk-/, /^cvr-/, /^wpcf7/],
    greedy: [/\[/], // 属性セレクタを含む規則は全部残す
  },
  keyframes: true,
  fontFace: true,
  // CSS変数（:root の --sm/--tab 等）は「var() で未参照」でも落とさない。落とすと
  // computedStyle が正本と一致しなくなり、visual-diff-theme-lp.mjs が差分として拾う（2026-09-04）。
  variables: false,
  rejected: REPORT,
});

// 先頭の /*! */ は esbuild の minify でも残る。生成元のハッシュを埋めて
// check-form-invariants.mjs が「theme-snapshot.css と生成物がズレていない」ことを見る。
const banner = `/*! theme-lp.css — generated by scripts/build-theme-lp-css.mjs from theme-snapshot.css@${srcHash}. Do not edit. */\n`;
// webpack/sass-loader が残した `/*!***...*!\` のビルド情報コメント（約500B・minifyでも残る）は落とす
const body = result.css.replace(/^\s*@charset[^;]*;\s*/i, "").replace(/\/\*![\s\S]*?\*\/\s*/g, "");
const css = banner + body;
writeFileSync(OUT, css);

console.log(`build-theme-lp-css: ${relative(ROOT, SRC)} (${source.length}B) → ${relative(ROOT, OUT)} (${css.length}B), content ${content.length} files, source@${srcHash}`);
if (REPORT && result.rejected) {
  console.log(`--- 落とした規則 ${result.rejected.length} 件 ---`);
  for (const sel of result.rejected) console.log("  " + sel);
}
